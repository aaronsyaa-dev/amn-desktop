export type CleCreer = keyof typeof EN;
export const { traduire, useMots, dictionnaires } = definirMots(EN, FR);

/** Cles qui se comptent : `<base>.1` existe. */
type BaseComptee = CleCreer extends infer K ? (K extends `${infer B}.1` ? B : never) : never;

/** Dit un compte : `.0` si la clé existe et n = 0 ; sinon singulier pour 0 et 1 en français (usage), pour 1 seulement en anglais ; `.n` au-delà. */
export function compte(langue: Langue, base: BaseComptee, n: number, params: ParamsMots = {}): string {
  const zero = `${base}.0` as CleCreer;
  const pluriel = langue === 'fr' ? Math.abs(n) >= 2 : n !== 1;
  const cle = (n === 0 && zero in EN ? zero : pluriel ? `${base}.n` : `${base}.1`) as CleCreer;
  return traduire(langue, cle, { n, ...params });
}
